"""Generates src/components/icons.ts: SVG path data for the icons Timi uses.

Timi used to load the whole Material Symbols Rounded variable font (5.4 MB) and draw icons by
ligature. This takes just the icons in ICON_NAMES from that same font, at the settings Timi
rendered with (weight 400, grade 0, optical size 20), outline and filled, so they look the same.

Add a name to ICON_NAMES, then run (Python 3, once: pip install fonttools brotli):

    python scripts/build-icons.py

The font comes from the @fontsource-variable/material-symbols-rounded dev dependency; it is only
read here and is not shipped in the app.
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource-variable/material-symbols-rounded/files/material-symbols-rounded-latin-full-normal.woff2"
OUT = ROOT / "src/components/icons.ts"

ICON_NAMES = [
    "add", "add_task", "apartment", "arrow_back", "arrow_forward", "bedtime", "calendar_month", "calendar_today", "category", "check", "check_circle",
    "chevron_left", "chevron_right", "close", "close_fullscreen", "cloud_done", "cloud_off", "confirmation_number",
    "content_copy", "delete", "drag_indicator", "edit_note", "error", "event", "expand_less", "expand_more", "flag", "folder", "groups",
    "history", "info", "link", "notifications", "notifications_active", "open_in_full", "pause", "play_arrow",
    "push_pin", "refresh", "replay", "schedule", "search", "settings", "snooze", "swap_horiz", "sync", "sync_problem", "timer",
    "videocam", "view_timeline", "volume_off", "volume_up", "wb_sunny", "width", "work",
]

# Extra weights, as their own names: the done check on task rows is drawn at weight 600 (1a)
EXTRA = {"check_bold": ("check", 600)}

AXES = {"GRAD": 0, "opsz": 20}


def ligature_glyphs(font: TTFont) -> dict[str, str]:
    """Icon name -> glyph name, from the font's ligature table."""
    cmap = font.getBestCmap()
    by_components = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if sub.LookupType == 7:
                sub = sub.ExtSubTable
            if type(sub).__name__ != "LigatureSubst":
                continue
            for first, entries in sub.ligatures.items():
                for lig in entries:
                    by_components[tuple([first] + lig.Component)] = lig.LigGlyph
    names = ICON_NAMES + [source for source, _ in EXTRA.values()]
    return {name: by_components[tuple(cmap[ord(c)] for c in name)] for name in names}


def number(value: float) -> str:
    """One decimal place: 0.1 of 960 units is far below a pixel at icon sizes."""
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def path_data(font: TTFont, glyph: str) -> str:
    glyph_set = font.getGlyphSet()
    pen = SVGPathPen(glyph_set, ntos=number)
    # Font y points up; SVG y points down. With viewBox "0 -960 960 960" the icon fills the box.
    glyph_set[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    return pen.getCommands()


def instance(fill: int, weight: int) -> TTFont:
    return instantiateVariableFont(TTFont(FONT), {**AXES, "FILL": fill, "wght": weight})


def main() -> None:
    glyphs = ligature_glyphs(TTFont(FONT))
    outline, filled = instance(0, 400), instance(1, 400)
    lines = [
        "// Generated by scripts/build-icons.py from Material Symbols Rounded (weight 400, optical size 20).",
        "// Do not edit by hand: add the name to ICON_NAMES in the script and run it again.",
        "",
        "/** SVG path data (viewBox 0 -960 960 960) for each icon: [outline, filled]. */",
        "export const ICONS = {",
    ]
    for name in ICON_NAMES:
        lines.append(f'  {name}: ["{path_data(outline, glyphs[name])}", "{path_data(filled, glyphs[name])}"],')
    for name, (source, weight) in EXTRA.items():
        heavy_outline, heavy_filled = instance(0, weight), instance(1, weight)
        lines.append(
            f'  {name}: ["{path_data(heavy_outline, glyphs[source])}", "{path_data(heavy_filled, glyphs[source])}"],'
        )
    lines += ["} as const;", "", "export type IconName = keyof typeof ICONS;", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(ICON_NAMES) + len(EXTRA)} icons to {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
